"""Renders the Graph map block of CONTRIBUTING.md from the compiled agent graph."""

import argparse
import sys
from pathlib import Path

from agent.graph import build_graph
from agent.graph_meta import EDGE_LABELS, NODE_META
from agent.state import AgentState

CONTRIBUTING = Path(__file__).resolve().parent.parent / "CONTRIBUTING.md"
START_MARKER = "<!-- graph-map:start -->"
END_MARKER = "<!-- graph-map:end -->"
COMMAND = "python -m scripts.render_graph_map"

# `end` is a Mermaid keyword, so the endpoints get safe ids.
_ENDPOINT_IDS = {"__start__": "graph_start", "__end__": "graph_end"}
_ENDPOINT_LABELS = {"__start__": "start", "__end__": "end"}
_KIND_FILLS = {
    "llm": "fill:#dbeafe,stroke:#2563eb,color:#111",
    "deterministic": "fill:#dcfce7,stroke:#16a34a,color:#111",
    "control": "fill:#fef3c7,stroke:#d97706,color:#111",
}
_LEGEND = {"llm": "LLM call", "deterministic": "deterministic", "control": "control"}


def _id(node: str) -> str:
    return _ENDPOINT_IDS.get(node, node)


def _mermaid(graph) -> str:
    lines = ["flowchart TB"]
    for node in graph.nodes:
        if node in _ENDPOINT_IDS:
            lines.append(f'    {_id(node)}(["{_ENDPOINT_LABELS[node]}"])')
        else:
            lines.append(f'    {node}["{node}"]:::{NODE_META[node].kind}')
    for edge in graph.edges:
        source, target = _id(edge.source), _id(edge.target)
        if edge.conditional:
            label = EDGE_LABELS[(edge.source, edge.target)]
            lines.append(f'    {source} -. "{label}" .-> {target}')
        else:
            lines.append(f"    {source} --> {target}")
    for kind, fill in _KIND_FILLS.items():
        lines.append(f"    classDef {kind} {fill}")
    lines.append("    subgraph legend")
    for kind, text in _LEGEND.items():
        lines.append(f'        legend_{kind}["{text}"]:::{kind}')
    lines.append("    end")
    return "\n".join(lines)


def _fields(names: tuple[str, ...]) -> str:
    return ", ".join(f"`{n}`" for n in names) or "—"


def _node_table() -> str:
    rows = ["| Node | Kind | Reads | Writes | What it does |", "|---|---|---|---|---|"]
    for node, meta in NODE_META.items():
        rows.append(
            f"| `{node}` | {meta.kind} | {_fields(meta.reads)} | {_fields(meta.writes)} | {meta.description} |"
        )
    return "\n".join(rows)


def _field_table() -> str:
    rows = ["| Field | Written by |", "|---|---|"]
    for field in AgentState.__annotations__:
        writers = [f"`{n}`" for n, m in NODE_META.items() if field in m.writes]
        rows.append(f"| `{field}` | {', '.join(writers) or '— (input)'} |")
    return "\n".join(rows)


def render() -> str:
    graph = build_graph().get_graph()
    return "\n\n".join(
        [
            f"<!-- generated by {COMMAND}; do not edit by hand -->",
            f"```mermaid\n{_mermaid(graph)}\n```",
            _node_table(),
            _field_table(),
        ]
    )


def current_block(text: str) -> str:
    if START_MARKER not in text or END_MARKER not in text:
        raise ValueError(f"CONTRIBUTING.md is missing {START_MARKER} / {END_MARKER}")
    return text.split(START_MARKER, 1)[1].split(END_MARKER, 1)[0].strip("\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if the block is stale")
    args = parser.parse_args()
    text = CONTRIBUTING.read_text()
    try:
        current = current_block(text)
    except ValueError as err:
        print(err, file=sys.stderr)
        return 1
    block = render()
    if args.check:
        if current != block:
            print(f"Graph map is stale: run {COMMAND}", file=sys.stderr)
            return 1
        return 0
    head, rest = text.split(START_MARKER, 1)
    tail = rest.split(END_MARKER, 1)[1]
    CONTRIBUTING.write_text(f"{head}{START_MARKER}\n{block}\n{END_MARKER}{tail}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
